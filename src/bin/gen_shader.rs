///  Generate verified multi-limb Mandelbrot WGSL expressions.
///
///  Demonstrates the full pipeline:
///  ArithLimb → generic_add_limbs/generic_mul_karatsuba → WGSL

use verus_fractals::gpu_codegen::{gen_add_exprs, gen_mul_exprs};
use verus_fractals::wgsl_codegen::expr_to_wgsl;

fn main() {
    let n: usize = 4;  // 4 limbs = 128-bit precision

    // Variable names for the limbs
    let var_names: Vec<String> = (0..2*n)
        .map(|k| if k < n { format!("a_{}", k) } else { format!("b_{}", k - n) })
        .collect();
    let var_refs: Vec<&str> = var_names.iter().map(|s| s.as_str()).collect();

    println!("// ═══════════════════════════════════════════════════");
    println!("// Verified {}-limb ({}-bit) carry-chain addition", n, n * 32);
    println!("// Generated by ArithLimb + generic_add_limbs pipeline");
    println!("// Correctness: proved once in verus-fixed-point (78 fns)");
    println!("// ═══════════════════════════════════════════════════");
    println!();

    // Generate verified N-limb addition
    let (sum_exprs, carry_expr) = gen_add_exprs(0, n as u32, n);

    for (k, expr) in sum_exprs.iter().enumerate() {
        let wgsl = expr_to_wgsl(expr, &var_refs);
        println!("let sum_{}: u32 = u32({});", k, wgsl);
    }
    println!("let carry: u32 = u32({});", expr_to_wgsl(&carry_expr, &var_refs));

    println!();
    println!("// ═══════════════════════════════════════════════════");
    println!("// Verified {}-limb Karatsuba multiply", n);
    println!("// O(n^1.585) — schoolbook for n<=4, Karatsuba for n>4");
    println!("// ═══════════════════════════════════════════════════");
    println!();

    // Generate verified N-limb Karatsuba multiply
    let mul_a_base = 0u32;
    let mul_b_base = n as u32;
    let mul_var_names: Vec<String> = (0..2*n)
        .map(|k| if k < n { format!("x_{}", k) } else { format!("y_{}", k - n) })
        .collect();
    let mul_var_refs: Vec<&str> = mul_var_names.iter().map(|s| s.as_str()).collect();

    let (prod_exprs, _gc) = gen_mul_exprs(mul_a_base, mul_b_base, n);

    for (k, expr) in prod_exprs.iter().enumerate() {
        let wgsl = expr_to_wgsl(expr, &mul_var_refs);
        println!("let prod_{}: u32 = u32({});", k, wgsl);
    }
}
